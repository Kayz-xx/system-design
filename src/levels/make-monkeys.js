// Regenerates monkey-scores.js after a level or the simulator changes: node src/levels/make-monkeys.js
// Each scene's 100 monkeys run on the same 1,000 random mornings the learner's design faces.
import { writeFileSync } from 'node:fs';
import { monkeyDesigns, mornings, survivalOf, MONKEYS, MORNINGS, SEED } from './audit.js';
import { LEVELS } from './levels.js';

const SCORES = {};
for (const l of LEVELS) {
  SCORES[l.id] = {};
  for (const w of ['cafe', 'software']) {
    const list = mornings(l.id, w);
    SCORES[l.id][w] = monkeyDesigns(l.id, w).map((d) => survivalOf(d, list));
    console.log(l.id, w, 'done');
  }
}
const rows = LEVELS.map((l) => `  ${l.id}: {\n${['cafe', 'software'].map((w) => `    ${w}: [${SCORES[l.id][w].join(', ')}]`).join(',\n')}\n  }`).join(',\n');
const body = `// Generated by src/levels/make-monkeys.js. Do not edit by hand; audit.test.js checks it.
// How many of ${MORNINGS} random mornings (seed ${SEED}) each of ${MONKEYS} random designs survives, per scene, in generation order.
export const MONKEY_SCORES = {
${rows}
};
`;
writeFileSync(new URL('./monkey-scores.js', import.meta.url), body);
console.log('wrote monkey-scores.js');
