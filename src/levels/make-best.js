// Regenerates best-designs.js after a level or the simulator changes: node src/levels/make-best.js
import { writeFileSync } from 'node:fs';
import { findBest } from './best.js';
import { LEVELS } from './levels.js';

const BEST = {};
for (const l of LEVELS) {
  BEST[l.id] = {};
  for (const w of ['cafe', 'software']) {
    const b = findBest(l.id, w);
    BEST[l.id][w] = b ? { cost: b.cost, design: b.design } : null;
  }
}
const body = `// Generated by src/levels/make-best.js. Do not edit by hand; best.test.js checks it.
// The cheapest design that passes every test of each scene, in software units and dollars an hour.
export const BEST = ${JSON.stringify(BEST, null, 2).replace(/"([a-zA-Z]+)":/g, '$1:').replace(/"/g, "'")};
`;
writeFileSync(new URL('./best-designs.js', import.meta.url), body);
console.log('wrote best-designs.js');
